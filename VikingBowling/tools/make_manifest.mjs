// Writes js/standin/manifest.js: every asset path under the folders the lane TV reads,
// keyed by its lower-case spelling. The theme XML files were written on Windows, where
// "V3GFX\Resource\..." and "v3gfx/Resource/..." are one file; a web server that matches
// case exactly (GitHub Pages) needs the real spelling, and tv-standin.js uses this table
// to ask for it.   node tools/make_manifest.mjs
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = {};
function walk(rel) {
  for (const name of readdirSync(join(root, rel))) {
    const r = rel ? rel + '/' + name : name;
    if (statSync(join(root, r)).isDirectory()) walk(r);
    else {
      out[r.toLowerCase()] = r;
    }
  }
}
for (const top of ['v3gfx', 'web/screen', 'GameConsole', 'Reception']) walk(top);
// The folder names alone, so a path asked for with another case of a folder still resolves
const text = '// Generated by tools/make_manifest.mjs - do not edit\nwindow.VIKING_ASSET_CASE = ' + JSON.stringify(out) + ';\n';
writeFileSync(join(root, 'js', 'standin', 'manifest.js'), text);
console.log(Object.keys(out).length + ' asset paths');

// The Auto formats (Reception/vbsTournaments/Auto/Hidden): every <name>.h001 header and
// <name>.r001 rule file as base64, so the game can offer them all without a directory
// listing (a static web server has none). The engine parses these bytes at run time.
import { readFileSync as rf, existsSync as ex } from 'node:fs';
const autoDir = join(root, 'Reception', 'vbsTournaments', 'Auto', 'Hidden');
const autos = [];
for (const f of readdirSync(autoDir).filter((n) => n.endsWith('.h001')).sort((a, b) => a.localeCompare(b, 'sv'))) {
  const name = f.slice(0, -5);
  const r = join(autoDir, name + '.r001');
  autos.push({ name, h: rf(join(autoDir, f)).toString('base64'), r: ex(r) ? rf(r).toString('base64') : '' });
}
const moves = readdirSync(join(root, 'Reception', 'vbsTournaments', 'PlayerMovements')).filter((n) => n.toLowerCase().endsWith('.ini'));
writeFileSync(join(root, 'js', 'vbst', 'autoformats.js'),
  '// Generated by tools/make_manifest.mjs from Reception/vbsTournaments - do not edit\n' +
  'export const AUTO_FORMATS = ' + JSON.stringify(autos) + ';\n' +
  'export const MOVEMENT_FILES = ' + JSON.stringify(moves) + ';\n');
console.log(autos.length + ' Auto formats, ' + moves.length + ' movement files');
