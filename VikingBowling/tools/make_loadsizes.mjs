// Writes js/loadsizes.js: every file the splash waits for before the game can start, with its
// size in bytes, for the load bar (js/loading.js). That is the style sheets and the picture
// index.html names, and the whole static import graph of its module scripts (bare names like
// 'three' resolved through the page's import map). import() is left out: it loads later, when
// used. Run it after a change to the JavaScript (tests/loading_test.mjs reports a list that is
// out of date); an old list only makes the bar's steps a little uneven.   node tools/make_loadsizes.mjs
import { readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, dirname, posix, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export function startupFiles() {
  const html = readFileSync(join(root, 'index.html'), 'utf8');
  const map = JSON.parse((html.match(/<script type="importmap">([\s\S]*?)<\/script>/) || [, '{}'])[1]).imports || {};
  const files = {};
  const add = (rel) => {
    if (rel in files) return false;
    files[rel] = statSync(join(root, rel)).size;     // throws on a name that is not there: better than a wrong list
    return true;
  };
  const resolveSpec = (spec, from) => {
    if (/^\.{0,2}\//.test(spec)) return posix.normalize(posix.join(posix.dirname(from), spec));
    if (map[spec]) return posix.normalize(map[spec]);
    for (const [k, v] of Object.entries(map)) if (k.endsWith('/') && spec.startsWith(k)) return posix.normalize(v + spec.slice(k.length));
    throw new Error(`${from}: cannot resolve '${spec}'`);
  };
  const walk = (rel) => {
    if (rel === 'js/loadsizes.js') return;            // this list itself: 2 KB, and its size depends on its contents
    if (!add(rel)) return;
    // an import or export ... from statement at the start of a line (so a comment about one is not taken for one)
    const src = readFileSync(join(root, rel), 'utf8');
    for (const m of src.matchAll(/^[ \t]*(?:import|export)\s*(?:[\w$*{},\s]+?\s*from\s*)?['"]([^'"\n]+)['"]/gm)) walk(resolveSpec(m[1], rel));
  };
  for (const m of html.matchAll(/<link rel="stylesheet" href="([^"]+)"/g)) add(m[1]);
  for (const m of html.matchAll(/<img [^>]*src="([^"]+)"/g)) add(m[1]);
  for (const m of html.matchAll(/<script type="module" src="([^"]+)"/g)) walk(m[1]);
  return files;
}

// run as a script (tests/loading_test.mjs imports startupFiles and writes nothing); Windows
// spells the drive letter either way
if (process.argv[1] && resolve(process.argv[1]).toLowerCase() === fileURLToPath(import.meta.url).toLowerCase()) {
  const files = startupFiles();
  const total = Object.values(files).reduce((a, b) => a + b, 0);
  writeFileSync(join(root, 'js', 'loadsizes.js'),
    '// Generated by tools/make_loadsizes.mjs - do not edit\n' +
    '// The files the splash waits for and their sizes in bytes (the load bar, js/loading.js)\n' +
    'export const LOAD_FILES = ' + JSON.stringify(files, null, 0).replace(/,"/g, ',\n  "').replace(/^\{/, '{\n  ').replace(/\}$/, '\n}') + ';\n');
  console.log(Object.keys(files).length + ' files, ' + total + ' bytes');
}
